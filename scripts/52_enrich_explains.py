# 1) 应用解析
applied = 0
for p in 'ABCDE':
    f = data('题库资料', 'answers', f'{p}卷.jsonl')
    rows = [json.loads(l) for l in open(f, encoding='utf-8') if l.strip()]
    for r in rows:
        if not r.get('corrected_from'):
            continue
        key = f"{p}{r['n']}"
        if key in E:
            r['explain'] = E[key]
            r['source'] = SRC
            applied += 1
        else:
            print('⚠ 缺解析:', key)
    with open(f, 'w', encoding='utf-8') as fp:
        for r in rows:
            fp.write(json.dumps(r, ensure_ascii=False) + '\n')
print('解析已应用:', applied, '/', len(E))

# 2) papers_raw 题型修正（线上表单为多选控件）
raw_path = data('题库资料', 'papers_raw.json')
papers = json.load(open(raw_path, encoding='utf-8'))
FIX = {('A卷', 58), ('C卷', 41), ('C卷', 51), ('D卷', 46), ('D卷', 48)}
fixed = 0
for name, p in papers.items():
    for it in p['items']:
        if (name, it['n']) in FIX and it['type'] != 'multi':
            it['type'] = 'multi'
            fixed += 1
json.dump(papers, open(raw_path, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('题型修正 single→multi:', fixed, '题')
